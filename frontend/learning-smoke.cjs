const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
app.setPath('userData', path.join(app.getPath('temp'), `paper-learning-smoke-${Date.now()}`));
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1440, height: 1100, show: false, webPreferences: { sandbox: true, contextIsolation: true } });
  const errors = [];
  win.webContents.on('console-message', (_event, level, message) => { if (level >= 3) errors.push(message); });
  const evaluate = code => win.webContents.executeJavaScript(code, true);
  const wait = async code => { for (let i = 0; i < 80; i++) { if (await evaluate(code)) return; await delay(150); } throw Error(`Timeout: ${code}`); };
  const click = async text => { const found = await evaluate(`(() => { const b = [...document.querySelectorAll('button')].find(b => b.textContent.includes(${JSON.stringify(text)}) && !b.disabled); if (!b) return false; b.click(); return true; })()`); assert(found, text); await delay(250); };
  const output = path.join(__dirname, 'out/learning-smoke'); fs.mkdirSync(output, { recursive: true });
  try {
    win.webContents.session.webRequest.onBeforeRequest({ urls: ['http://127.0.0.1:8000/*'] }, (details, callback) => callback({ redirectURL: details.url.replace(':8000/', ':8011/') }));
    await win.loadURL('http://127.0.0.1:5173');
    await wait(`document.querySelector('.status-online') !== null`);
    await click('试卷模板');
    await wait(`document.querySelector('.agent-toggle input') !== null`);
    assert.equal(await evaluate(`document.querySelectorAll('.template-list-item').length`), 3);
    assert.equal(await evaluate(`[...document.querySelectorAll('.toolbar-actions button')].some(b => b.textContent.includes('增加 408 模板套件'))`), true);
    await evaluate(`document.querySelector('.agent-toggle input').click()`);
    await wait(`document.querySelector('dialog[open]') !== null`);
    assert.equal(await evaluate(`document.querySelector('input[type=password]').type`), 'password');
    fs.writeFileSync(path.join(output, 'agent-dialog.png'), (await win.webContents.capturePage()).toPNG());
    await click('取消');
    assert.equal(await evaluate(`document.querySelector('.agent-toggle input').checked`), false);
    await evaluate(`document.querySelector('.agent-toggle input').click()`);
    await wait(`document.querySelector('dialog[open]') !== null`);
    await evaluate(`(() => { const fields = document.querySelectorAll('dialog input'); const values = ['https://example.com/v1', 'test-model', 'smoke-secret']; fields.forEach((field, i) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(field, values[i]); field.dispatchEvent(new Event('input', { bubbles: true })); }); })()`);
    await click('确认配置');
    await click('保存模板');
    await wait(`document.querySelector('.notice')?.textContent.includes('模板已保存')`);
    assert.equal(await evaluate(`document.querySelector('.agent-toggle input').checked`), true);
    assert.equal(await evaluate(`JSON.stringify(localStorage).includes('smoke-secret')`), false);
    assert.equal(await evaluate(`fetch('http://127.0.0.1:8011/api/templates').then(r => r.text()).then(s => s.includes('smoke-secret'))`), false);
    await evaluate(`document.querySelector('.agent-toggle input').click()`);
    await click('保存模板');
    await click('增加 408 模板套件');
    await wait(`document.querySelectorAll('.template-list-item').length === 8`);
    await click('增加 408 模板套件');
    assert.equal(await evaluate(`document.querySelectorAll('.template-list-item').length`), 8);
    fs.writeFileSync(path.join(output, 'templates.png'), (await win.webContents.capturePage()).toPNG());
    await click('小题狂练');
    assert.equal(await evaluate(`document.querySelector('.learning-panel') === null`), true);
    await evaluate(`(() => {const field = document.querySelector('.practice-fields select'); Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set.call(field, '计算机408'); field.dispatchEvent(new Event('change', {bubbles: true}));})()`);
    await delay(500);
    await click('开始随机刷题');
    await wait(`document.querySelector('.answer-card') !== null`);
    await click('标记此题');
    await evaluate(`document.querySelector('.practice-option').click()`);
    await click('提交答案');
    await wait(`document.querySelector('.question-reflection') !== null`);
    await wait(`!document.querySelector('.question-reflection input').disabled`);
    await evaluate(`(() => { const input = document.querySelector('.question-reflection input'); if (!input.checked) input.click(); })()`);
    await click('保存复盘');
    await wait(`document.querySelector('.question-reflection').textContent.includes('已保存')`);
    fs.writeFileSync(path.join(output, 'practice.png'), (await win.webContents.capturePage()).toPNG());
    await win.reload(); await delay(1500);
    await click('小题狂练');
    await wait(`document.querySelector('.answer-card')?.textContent.includes('★')`);
    await wait(`document.querySelector('.question-reflection') !== null`);
    await wait(`!document.querySelector('.question-reflection input').disabled`);
    assert.equal(await evaluate(`document.querySelector('.question-reflection input').checked`), true);
    win.setSize(390, 844); await delay(500);
    fs.writeFileSync(path.join(output, 'mobile.png'), (await win.webContents.capturePage()).toPNG());
    const overflow = await evaluate(`({ body: document.body.scrollWidth, viewport: innerWidth })`);
    console.log(JSON.stringify({ status: 'passed', checks: ['agent dialog cancel', '408 presets', 'learning panel hidden', 'answer and reflection', 'favorite persistence', 'reload draft and marks'], overflow, errors, screenshots: output }));
    assert.deepEqual(errors, []);
  } catch (error) { console.error(error); win.destroy(); app.exit(1); return; }
  win.destroy(); app.quit();
});
